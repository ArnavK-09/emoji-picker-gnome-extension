export const ALL_EMOJIS = (() => {
  const flat = [];
  for (const category of CATEGORIES) {
    for (const emoji of category.emojis) {
      flat.push({
        char: emoji.c,
        name: emoji.n,
        keywords: (emoji.k || '').split(' '),
        category: category.id,
        tone: emoji.t === true,
      });
    }
  }
  return flat;
})();

export const EMOJI_BY_CHAR = (() => {
  const map = new Map();
  for (const emoji of ALL_EMOJIS) map.set(emoji.char, emoji);
  return map;
})();

export const CATEGORY_BY_ID = (() => {
  const map = new Map();
  for (const category of CATEGORIES) map.set(category.id, category);
  return map;
})();

export function applySkinTone(char, tone) {
  const emoji = EMOJI_BY_CHAR.get(char);
  const modifier = SKIN_TONE_MODIFIER[tone] ?? "";
  if (!emoji || !emoji.tone || !modifier) return char;
  return char + modifier;
}
